import assert from "node:assert/strict";
import { coachPlan } from "./planning-coach";
import { emptyPlan, planStorageKey, planningQuestion, restorePlan, suggestedPlanner } from "./writing-plan";

assert.equal(suggestedPlanner("opinion"), "opinion");
assert.equal(suggestedPlanner("creative"), "story");
assert.equal(suggestedPlanner("informative"), "web");
const plan = emptyPlan("opinion");
plan.opinion[0] = "School should start later.";
plan.ideas[0] = "More rest";
plan.kind = "web";
assert.deepEqual(restorePlan(JSON.stringify(plan), "opinion"), plan);
assert.deepEqual(restorePlan("broken json", "opinion"), emptyPlan("opinion"));
assert.deepEqual(restorePlan('{"version":1,"kind":"web","ideas":null}', "opinion"), emptyPlan("opinion"));
assert.notEqual(planStorageKey("a", "Topic", "Body", "opinion"), planStorageKey("b", "Topic", "Body", "opinion"));
assert.notEqual(planStorageKey("a", "Topic", "Body", "opinion"), planStorageKey("a", "Topic", "Other", "opinion"));
plan.kind = "opinion";
assert.match(planningQuestion(plan), /reason/);
plan.opinion[1] = "Students need rest.";
assert.match(planningQuestion(plan), /example/);
assert.equal(restorePlan(JSON.stringify(plan), "opinion").opinion[0], "School should start later.");
console.log("Writing planner persistence and guidance tests passed.");

const web = emptyPlan("informative");
assert.match(coachPlan(web).question, /topic/);
assert.doesNotMatch(coachPlan(web).observation, /collected|chose/);
web.topic = "Fall";
web.ideas = ["Red leaves", "Cool weather", ""];
assert.match(coachPlan(web).observation, /2 ideas about "Fall"/);
assert.match(coachPlan(web).question, /Red leaves/);
web.ideas[1] = "red leaves";
assert.match(coachPlan(web).question, /same/);
const story = emptyPlan("narrative");
story.story[0] = "Maya";
story.story[3] = "The bridge is gone";
story.skipped = ["story:1", "story:2"];
assert.match(coachPlan(story).observation, /Maya.*The bridge is gone/);
assert.match(coachPlan(story).question, /character try next/);
story.story[4] = "Builds a raft";
assert.match(coachPlan(story).question, /story end/);
assert.deepEqual(restorePlan(JSON.stringify(story), "narrative"), story);
const opinion = emptyPlan("opinion");
opinion.opinion[0] = "School should start later";
opinion.opinion[1] = "Students need more rest";
assert.match(coachPlan(opinion).question, /Students need more rest.*example/);
opinion.skipped = ["opinion:2"];
assert.match(coachPlan(opinion).question, /at the end/);
opinion.opinion[7] = "Later mornings help us";
assert.doesNotMatch(coachPlan(opinion).question, /another reason|Reason 2|Reason 3/);
const unchanged = JSON.stringify(opinion);
coachPlan(opinion);
assert.equal(JSON.stringify(opinion), unchanged);
opinion.opinion[1] = "Studnts need mor rest";
assert.doesNotMatch(coachPlan(opinion).question, /spell|grammar|mistake/i);
assert.deepEqual(restorePlan(JSON.stringify({ ...story, skipped: ["invalid"] }), "narrative"), emptyPlan("narrative"));
console.log("Planning coach checks passed: grounded feedback, next steps, skipped sections, and original notes preserved.");
